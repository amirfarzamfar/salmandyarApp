export function getDrugContent(tab: DrugCalculationTab): DrugContent {
  return DRUG_CONTENT[tab];
}

export function getAllDrugFAQs() {
  return DRUG_TAB_ORDER.flatMap(tab =>
    DRUG_CONTENT[tab].faqs.map(f => ({
      id: Number(`${tab.length}${f.id.toString().padStart(3, '0')}`),
      question: f.question,
      answer: `[${DRUG_CONTENT[tab].persianName}] ${f.answer}`,
      displayOrder: f.id,
    })),
  );
}
